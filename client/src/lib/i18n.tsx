export const DICTS: Record<Lang, Dict> = { en, ar };

export const fill = (text: string, values: Record<string, string | number>) => text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));

function make(lang: Lang, setLang: (lang: Lang) => void) {
  const locale = lang === "ar" ? "ar-EG-u-nu-latn" : "en-GB";
  const number = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });
  const dateFormat = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", year: "numeric", timeZone: "Africa/Cairo" });
  const dayFormat = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", timeZone: "UTC" });
  return {
    lang,
    dir: lang === "ar" ? ("rtl" as const) : ("ltr" as const),
    t: DICTS[lang],
    setLang,
    fill,
    pick: (value: Localized) => value[lang] || value.en,
    n: (value: number) => number.format(value),
    money: (piastres: number) => (lang === "ar" ? `${number.format(piastres / 100)} ج.م` : `EGP ${number.format(piastres / 100)}`),
    date: (iso: string) => dateFormat.format(new Date(iso)),
    day: (key: string) => dayFormat.format(new Date(`${key}T12:00:00Z`)),
    plural: (forms: { one: string; other: string }, count: number) => fill(count === 1 ? forms.one : forms.other, { n: number.format(count) }),
  };
}

export type I18n = ReturnType<typeof make>;

const Context = createContext<I18n | null>(null);

function stored(): Lang {
  try {
    return localStorage.getItem("khayt:lang") === "ar" ? "ar" : "en";
  } catch {
    return "en";
  }
}

